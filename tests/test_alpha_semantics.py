"""Contract-authored expectations: these values precede the alpha evaluator."""
import copy
import itertools
import json
import unittest
from pathlib import Path

from bilqis_alpha.semantics import (
    ABI, LABELS, SemanticError, atom, combine, constant, evaluate, negate,
    normalize, quantify, sid, variable, world_from_states,
)
from bilqis_alpha.codec import decode, encode, token_manifest
from bilqis_alpha.data import audit_cases, build_corpus, composition, known_cases


class AlphaSemanticTests(unittest.TestCase):
    def semantic(self, states, query):
        return {"abi": ABI, "world": world_from_states(states), "query": query}

    def test_contract_authored_four_state_truth_tables(self):
        # Explicit Belnap-Dunn truth-order tables, not generated by the oracle.
        tables = {
            "and": [["TRUE", "FALSE", "UNKNOWN", "CONFLICT"],
                    ["FALSE", "FALSE", "FALSE", "FALSE"],
                    ["UNKNOWN", "FALSE", "UNKNOWN", "FALSE"],
                    ["CONFLICT", "FALSE", "FALSE", "CONFLICT"]],
            "or": [["TRUE", "TRUE", "TRUE", "TRUE"],
                   ["TRUE", "FALSE", "UNKNOWN", "CONFLICT"],
                   ["TRUE", "UNKNOWN", "UNKNOWN", "TRUE"],
                   ["TRUE", "CONFLICT", "TRUE", "CONFLICT"]],
        }
        for i, j in itertools.product(range(4), repeat=2):
            for op, table in tables.items():
                q = combine(op, atom("a", "b"), atom("b", "a"))
                self.assertEqual(evaluate(self.semantic([2, i, j, 2], q)), table[i][j])
        for i, expected in enumerate(("FALSE", "TRUE", "UNKNOWN", "CONFLICT")):
            self.assertEqual(evaluate(self.semantic([2, i, 2, 2], negate(atom("a", "b")))), expected)

    def test_named_known_pass_and_injected_defect(self):
        cases = known_cases()
        self.assertGreater(len(cases), 8)
        audit_cases(cases)
        defective = copy.deepcopy(cases)
        next(c for c in defective if c["id"] == "K03-unknown")["expected"] = "FALSE"
        with self.assertRaisesRegex(ValueError, "K03-unknown"):
            audit_cases(defective)

    def test_quantifier_scope_role_and_binding(self):
        w = world_from_states([0, 0, 1, 1])
        q = atom(variable("x"), constant("b"))
        expected = {"exists": "TRUE", "forall": "FALSE"}
        for op in expected:
            self.assertEqual(evaluate({"abi": ABI, "world": w, "query": quantify(op, q)}), expected[op])
        left = negate(quantify("exists", q))
        right = quantify("exists", negate(q))
        self.assertEqual(evaluate({"abi": ABI, "world": w, "query": left}), "FALSE")
        self.assertEqual(evaluate({"abi": ABI, "world": w, "query": right}), "TRUE")
        self.assertEqual(evaluate(self.semantic([2, 0, 1, 2], atom("a", "b"))), "TRUE")
        self.assertEqual(evaluate(self.semantic([2, 0, 1, 2], atom("b", "a"))), "FALSE")

    def test_unsupported_illegal_missing_and_unknown_do_not_collide(self):
        good = self.semantic([2] * 4, atom("a", "b"))
        self.assertEqual(evaluate(good), "UNKNOWN")
        bad = []
        bad.append(dict(good, query={"op": sid("implies"), "args": []}))
        bad.append(dict(good, query=atom(variable("x"), constant("b"))))
        bad.append(dict(good, query={"op": sid("not"), "args": []}))
        bad.append(dict(good, query=atom("c", "b")))
        bad.append(dict(good, answer="TRUE"))
        bad.append({"abi": ABI, "query": good["query"]})
        bad.append(dict(good, abi="bilqis-finite-world-0.1.0"))
        for s in bad:
            with self.assertRaises(SemanticError):
                evaluate(s)
        with self.assertRaises(SemanticError) as cm:
            evaluate(bad[0])
        self.assertEqual(cm.exception.code, "UNSUPPORTED_CONSTRUCT")

    def test_registry_signatures_and_schema(self):
        import jsonschema
        root = Path(__file__).resolve().parents[1]
        registry = json.loads((root / "fixtures/alpha/semantic-registry.json").read_text())
        ids = [r["id"] for r in registry["entries"]]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertTrue(all(r["sources"] for r in registry["entries"]))
        schema = json.loads((root / "schemas/alpha-semantic.schema.json").read_text())
        jsonschema.Draft202012Validator.check_schema(schema)
        for case in known_cases():
            jsonschema.validate(normalize(case["semantic"]), schema)
        with self.assertRaises(jsonschema.ValidationError):
            jsonschema.validate(dict(known_cases()[0]["semantic"], label="TRUE"), schema)

    def test_lossless_codec_canonical_equivalence_and_negative_tokens(self):
        for case in known_cases():
            s = normalize(case["semantic"])
            self.assertEqual(decode(encode(s)), s)
            swapped = copy.deepcopy(s)
            swapped["world"]["facts"].reverse()
            self.assertEqual(encode(swapped), encode(s))
        s = self.semantic([0, 1, 2, 3], combine("and", atom("a", "b"), atom("b", "a")))
        t = copy.deepcopy(s)
        t["query"]["args"].reverse()
        self.assertEqual(normalize(s), normalize(t))
        for ids in ([True], [-1], [len(token_manifest()["tokens"])], encode(s)[:-1], encode(s) + [0]):
            with self.assertRaises(ValueError):
                decode(ids)

    def test_frozen_composition_holdout_not_random_template_split(self):
        corpus = build_corpus()
        self.assertEqual(corpus, build_corpus())
        groups = {k: [r for r in corpus["cases"] if r["split"] == k] for k in ("TRAIN", "DEV", "HELDOUT")}
        patterns = {k: {composition(r["semantic"]["query"]) for r in rows} for k, rows in groups.items()}
        self.assertFalse(patterns["TRAIN"] & patterns["HELDOUT"])
        self.assertEqual(patterns["DEV"], patterns["TRAIN"])
        identities = {k: {json.dumps(normalize(r["semantic"]), sort_keys=True) for r in rows} for k, rows in groups.items()}
        self.assertFalse(identities["TRAIN"] & identities["DEV"])
        self.assertFalse(identities["TRAIN"] & identities["HELDOUT"])
        for rows in groups.values():
            self.assertEqual({r["expected"] for r in rows}, set(LABELS))
        audit_cases(corpus["cases"])


if __name__ == "__main__":
    unittest.main()
