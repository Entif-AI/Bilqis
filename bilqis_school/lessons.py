"""One shared lesson compiler for spiralling old, present, and future grades.

The teacher may mutate *selection*, never oracle answers or semantic laws.
Every row is generated by an existing oracle-backed executable mechanism.
"""
from __future__ import annotations

import random

from bilqis_micro import data as micro
from bilqis_development import data as development, kernel as semantics
from bilqis_u7e.lessons import build as lineage_build, validate_pair
from . import arithmetic
from .grades import skill_tree

SUPPORTED = {
    11: ("set-membership", "set-subset"),
    12: ("set-intersection", "set-difference"),
    13: ("function-domain", "function-range", "function-inverse"),
    14: ("function-composition",),
    15: ("graph-neighborhood", "graph-path"),
    16: ("provenance-ancestry",),
    18: ("current-evidence", "historical-evidence"),
}


class TeacherLibrary:
    def __init__(self):
        self.grades = {grade.number: grade for grade in skill_tree()}
        # The paired generator is expensive enough to cache and must not
        # silently truncate a contrast or drop CURRENT_STATE/DEPENDENCY.
        self.direct = lineage_build(251051,110,compositional=False)
        self.chains = lineage_build(251057,110,compositional=True)

    def ready(self, grade_number):
        return self.grades[grade_number].ready

    def compiled(self):
        return tuple(g.number for g in self.grades.values() if g.ready)

    def relation_pair(self, relation, rng, *, depth):
        pool=self.chains if depth>=3 else self.direct
        pair=list(rng.choice(pool["episodes"][relation]))
        validate_pair(pair[0],pair[1])
        return pair

    def one(self, grade: int, rng, *, depth: int = 1,
            prefer_composition: bool = False, truth=None):
        if not self.ready(grade):
            raise ValueError(f"GRADE_{grade:02d}_HAS_NO_EXECUTABLE_COMPILER")
        if 19 <= grade <= 22:
            return arithmetic.lesson(grade,rng,correct=truth,depth=depth)
        if grade == 17:
            relation=rng.choice(("DERIVED_FROM","DERIVED_FROM","SUPERSEDES",
                                 "DEPENDENCY","DEPENDENCY","CURRENT_STATE","REVISES"))
            return self.relation_pair(relation,rng,depth=depth)
        category="composition" if prefer_composition else "focus"
        if grade <= 10:
            stage=0 if grade<=3 else 1 if grade<=5 else 2 if grade<=8 else 3 if grade==9 else 4
            return micro.lesson(stage,rng,category=category,varied=depth>=4)
        if grade in SUPPORTED:
            stage=5 if grade<=15 else 6
            family=rng.choice(SUPPORTED[grade])
            return development.lesson(stage,family,rng,category=category,varied=depth>=4)
        raise ValueError(f"GRADE_{grade:02d}_NO_COMPILER_DISPATCH")


def valid_rows(rows, graph):
    if not rows:
        raise ValueError("NO_REAL_TEACHER_LESSONS")
    for row in rows:
        record=row["input"]
        if record.get("task") == arithmetic.VERSION:
            ids=arithmetic.encode(record,{token:i for i,token in enumerate(graph["tokens"])})
            if (arithmetic.evaluate(record["expression"]) !=
                arithmetic.independent_evaluate(record["expression"])):
                raise ValueError("SCHOOL_MATH_ORACLE_DRIFT")
        else:
            if semantics.evaluate(record) != semantics.independent_evaluate(record):
                raise ValueError("INHERITED_ORACLE_DRIFT")
            ids=semantics.encode(record)
        if len(ids)>96 or max(ids)>=len(graph["tokens"]):
            raise ValueError("SCHOOL_CODEC_CONTEXT_OR_VOCAB_INVALID")
        gold = ("TRUE" if arithmetic.evaluate(record["expression"]) else "FALSE") if (
            record.get("task")==arithmetic.VERSION) else semantics.evaluate(record)
        if row["gold"] != gold:
            raise ValueError("TRAIN_TARGET_NOT_ORACLE_CORRECT")


def encode(row, graph):
    record=row["input"]
    if record.get("task") == arithmetic.VERSION:
        return arithmetic.encode(record,{token:i for i,token in enumerate(graph["tokens"])})
    return semantics.encode(record)


def _fill_rows(library, grade, count, rng, *, depth, prefer_composition):
    result=[]
    attempts=0
    for index in range(count):
        if len(result)>=count:break
        while True:
            attempts+=1
            if attempts>count*100:
                raise ValueError("TEACHER_CANNOT_GENERATE_VALID_LESSON")
            try:
                if grade==17 and count>1:
                    cycle=("DERIVED_FROM","SUPERSEDES","DEPENDENCY",
                           "CURRENT_STATE","REVISES")
                    packet=library.relation_pair(cycle[(len(result)//2)%len(cycle)],
                                                 rng,depth=depth)
                else:
                    packet=library.one(grade,rng,depth=depth,
                                       prefer_composition=prefer_composition,
                                       truth=bool(index%2) if grade>=19 else None)
                break
            except ValueError as error:
                # Existing canonical random lesson creators reject worlds that
                # cannot be encoded or an inverse that's not a function.
                message=str(error)
                if ("world exceeds preserved context" not in message and
                    "inverse is not a function" not in message and
                    "context" not in message.lower()):
                    raise
        if isinstance(packet,list):
            for row in packet:
                if len(result)<count:result.append(row)
        else:
            result.append(packet)
    while len(result)<count:
        result += _fill_rows(library,grade,count-len(result),rng,
                             depth=depth,prefer_composition=prefer_composition)
    return result[:count]


def compose_batch(library, grade, strategy, graph, rng):
    """32 examples with real overlap of old skills and next-two-grade preview.

    A pair is an indivisible semantic unit, and every slot's grade of origin
    is recorded. There is no leftover truncation like the previous U7F code.
    """
    definition=library.grades[grade]
    previous=[g for g in range(1,grade) if library.ready(g)]
    future=[int(identifier[1:]) for identifier in definition.foreshadows
            if library.ready(int(identifier[1:]))]
    old_count=strategy["old"] if previous else 0
    next_count=strategy["preview"] if future else 0
    current_count=32-old_count-next_count
    if current_count<8 or current_count>32:
        raise ValueError("INVALID_STRATEGY_BATCH_COUNTS")
    if grade==17 and current_count%2:
        # preserve paired relation witnesses; extra current slot becomes old
        old_count+=1;current_count-=1
    items=[]
    def add(origin, count, depth, composition):
        if not count:return
        generated=_fill_rows(library,origin,count,rng,depth=depth,
                             prefer_composition=composition)
        items.extend((origin,row) for row in generated)
    add(grade,current_count,strategy["depth"],strategy["contrast"]>=.5)
    if previous:
        # Old material spans several grades, including one long-range anchor,
        # rather than focusing only on the current grade's immediate parent.
        directed=[int(identifier[1:]) for identifier in definition.rehearsal
                  if library.ready(int(identifier[1:]))]
        weighted = directed*2 + [previous[-1]]*3 + previous[-min(4,len(previous)):]
        if len(previous)>5:weighted += previous[:len(previous)-4:4]
        for _ in range(old_count):
            candidate=rng.choice(weighted)
            add(candidate,1,2,strategy["contrast"]>=.5)
    if future:
        for _ in range(next_count):
            add(rng.choice(future),1,1,False)
    if len(items)!=32:
        raise ValueError("SEMANTIC_BATCH_ALLOCATION_INCORRECT")
    valid_rows([row for _,row in items],graph)
    counts={"current":sum(n==grade for n,_ in items),
            "old":sum(n<grade for n,_ in items),
            "preview":sum(n>grade for n,_ in items)}
    if sum(counts.values())!=32:
        raise ValueError("INSTRUCTION_HAS_UNOWNED_ROWS")
    return [row for _,row in items],counts
